"""Builds the review steps shown with every assessment.

The steps describe what actually ran: guardrail actions and the tool calls the
agent made. They are written by the backend, not by the model, so the trail
cannot be invented.
"""

from .guardrails.corrections import Corrections
from .guardrails.input import PreparedInput


def build(prepared: PreparedInput, tool_calls: list[dict], model: str, corrections: Corrections) -> list[str]:
    steps = [_input_step(prepared)]
    steps.extend(_tool_step(call) for call in tool_calls)
    steps.append(f"Structured assessment generated by {model}.")
    steps.append(
        f"Output guardrails: {corrections.quotes_verified} evidence quote(s) verified against the scenario, "
        f"{corrections.quotes_removed} removed, {corrections.status_changes} status change(s)."
    )
    steps.append("Preliminary result: a governance reviewer must confirm it before any deployment decision.")
    return steps


def _input_step(prepared: PreparedInput) -> str:
    redacted = sum(prepared.redactions.values())
    injection = (
        "prompt-injection patterns flagged."
        if prepared.injection_signals
        else "no prompt-injection patterns found."
    )
    return f"Input guardrails applied: {redacted} sensitive value(s) redacted; {injection}"


def _tool_step(call: dict) -> str:
    if call["is_error"]:
        return f"Agent tool call failed: {call['tool']}."
    if call["tool"] == "list_requirements":
        return "Agent retrieved the governance requirement catalog."
    if call["tool"] == "get_requirement_guidance":
        ids = ", ".join(call["input"].get("requirement_ids", [])) or "none"
        return f"Agent retrieved assessment guidance for {ids}."
    if call["tool"] == "scan_risk_signals":
        return "Agent ran the risk-signal scan."
    return f"Agent called {call['tool']}."
