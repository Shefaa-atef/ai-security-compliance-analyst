"""Assessment pipeline: input guardrails -> agent -> output guardrails -> audit."""
import uuid
from collections import Counter

from . import audit, output_guardrails, risk_signals
from .agent import AssessmentAgent, AssessmentUnavailable
from .input_guardrails import prepare_input
from .schemas import MIN_SCENARIO_CHARS, AssessmentResponse


class ScenarioRejected(ValueError):
    """The scenario is unusable after input guardrails (for example, only whitespace)."""


def _signal_names(signals: dict) -> str:
    return ", ".join(key.replace("_", " ") for key in signals) or "none detected"


def _review_steps(prepared, tool_calls, model, guarded) -> list[str]:
    """Describe what actually ran. Built by the backend, not written by the model."""
    redacted = sum(prepared.redactions.values())
    steps = [
        f"Input guardrails applied: {redacted} sensitive value(s) redacted; "
        + ("prompt-injection patterns flagged." if prepared.injection_signals else "no prompt-injection patterns found.")
    ]
    for call in tool_calls:
        if call["is_error"]:
            steps.append(f"Agent tool call failed: {call['tool']}.")
        elif call["tool"] == "list_requirements":
            steps.append("Agent retrieved the governance requirement catalog.")
        elif call["tool"] == "get_requirement_guidance":
            ids = ", ".join(call["input"].get("requirement_ids", [])) or "none"
            steps.append(f"Agent retrieved assessment guidance for {ids}.")
        elif call["tool"] == "scan_risk_signals":
            steps.append("Agent ran the risk-signal scan.")
    steps.append(f"Structured assessment generated by {model}.")
    steps.append(
        f"Output guardrails: {guarded.quotes_verified} evidence quote(s) verified against the scenario, "
        f"{guarded.quotes_removed} removed, {guarded.status_changes} status change(s)."
    )
    steps.append("Preliminary result: a governance reviewer must confirm it before any deployment decision.")
    return steps


def assess(scenario: str, agent: AssessmentAgent, audit_path: str) -> AssessmentResponse:
    assessment_id = str(uuid.uuid4())
    prepared = prepare_input(scenario)
    base_event = {
        "assessment_id": assessment_id,
        "scenario_sha256": audit.scenario_hash(prepared.text),
        "scenario_chars": len(prepared.text),
        "redactions": prepared.redactions,
        "injection_flagged": bool(prepared.injection_signals),
    }

    if len(prepared.text) < MIN_SCENARIO_CHARS:
        audit.write(audit_path, {**base_event, "outcome": "rejected_input"})
        raise ScenarioRejected("Scenario is too short after cleanup")

    signals = risk_signals.scan(prepared.text)
    try:
        run = agent.run(prepared.text)
    except AssessmentUnavailable as exc:
        audit.write(audit_path, {**base_event, "outcome": "ai_unavailable", "reason": str(exc)})
        raise

    guarded = output_guardrails.apply(run.assessment, prepared.text, signals)
    final = guarded.assessment
    response = AssessmentResponse(
        **final.model_dump(),
        assessment_id=assessment_id,
        review_steps=_review_steps(prepared, run.tool_calls, run.model, guarded),
        guardrail_notes=prepared.notes + guarded.notes,
        model=run.model,
    )

    audit.write(audit_path, {
        **base_event,
        "outcome": "completed",
        "model": run.model,
        "tool_calls": [c["tool"] for c in run.tool_calls],
        "risk_signals": list(signals),
        "risk_level": final.risk_level,
        "status_counts": dict(Counter(f.status for f in final.findings)),
        "guardrail_notes": response.guardrail_notes,
    })
    return response
